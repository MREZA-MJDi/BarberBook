<?php

namespace App\Http\Controllers;

use App\Models\Salon;
use chillerlan\QRCode\Output\QRMarkupSVG;
use chillerlan\QRCode\QRCode;
use chillerlan\QRCode\QROptions;
use Illuminate\Contracts\View\View;
use Illuminate\Http\RedirectResponse;
use Illuminate\Http\Response;
use Illuminate\Support\Facades\Auth;
use Illuminate\Support\Str;

class QrController extends Controller
{
    /*
    |--------------------------------------------------------------------------
    | Index
    |--------------------------------------------------------------------------
    */

    /**
     * Display salon QR dashboard.
     */
    public function index(): View
    {
        /*
        |--------------------------------------------------------------------------
        | Current Salon
        |--------------------------------------------------------------------------
        */

        $salon = Auth::user()?->salon;

        abort_if(
            !$salon,
            404
        );


        /*
        |--------------------------------------------------------------------------
        | QR SVG
        |--------------------------------------------------------------------------
        */

        $qrSvg = null;


        /*
        |--------------------------------------------------------------------------
        | Render Existing QR
        |--------------------------------------------------------------------------
        |
        | qr_token فقط مشخص می‌کند QR برای این سالن ساخته شده است.
        | محتوای واقعی QR از public slug URL ساخته می‌شود.
        |
        */

        if (
            filled(
                $salon->qr_token
            )
        ) {

            $publicUrl =
                $this->publicUrl(
                    $salon
                );


            $qrSvg =
                $this->renderQr(
                    $publicUrl,
                    8
                );
        }


        /*
        |--------------------------------------------------------------------------
        | View
        |--------------------------------------------------------------------------
        */

        return view(
            'dashboard.qr.index',
            [
                'salon' =>
                    $salon,

                'qrSvg' =>
                    $qrSvg,
            ]
        );
    }


    /*
    |--------------------------------------------------------------------------
    | Generate
    |--------------------------------------------------------------------------
    */

    /**
     * Generate unique QR token.
     *
     * Important:
     * The QR token is stored in database,
     * but the public QR URL uses salon slug.
     */
    public function generate(): RedirectResponse
    {
        /*
        |--------------------------------------------------------------------------
        | Current Salon
        |--------------------------------------------------------------------------
        */

        $salon = Auth::user()?->salon;

        abort_if(
            !$salon,
            404
        );


        /*
        |--------------------------------------------------------------------------
        | Prevent Duplicate Generation
        |--------------------------------------------------------------------------
        */

        if (
            filled(
                $salon->qr_token
            )
        ) {

            return redirect()
                ->route(
                    'qr.index'
                )
                ->with(
                    'info',
                    'QR Code سالن شما قبلاً ساخته شده است.'
                );
        }


        /*
        |--------------------------------------------------------------------------
        | Generate Unique QR Token
        |--------------------------------------------------------------------------
        */

        do {

            $token =
                'BB-' .
                strtoupper(
                    Str::random(16)
                );

        } while (
            Salon::query()
                ->where(
                    'qr_token',
                    $token
                )
                ->exists()
        );


        /*
        |--------------------------------------------------------------------------
        | Save Token
        |--------------------------------------------------------------------------
        */

        $salon->update([
            'qr_token' =>
                $token,
        ]);


        /*
        |--------------------------------------------------------------------------
        | Success
        |--------------------------------------------------------------------------
        */

        return redirect()
            ->route(
                'qr.index'
            )
            ->with(
                'success',
                'QR Code سالن شما با موفقیت ساخته شد.'
            );
    }


    /*
    |--------------------------------------------------------------------------
    | Public URL
    |--------------------------------------------------------------------------
    */

    /**
     * Build public salon URL.
     *
     * New URL:
     *
     * /salon/{slug}
     *
     * Example:
     *
     * /salon/alijenab
     */
    private function publicUrl(
        Salon $salon
    ): string {
        return route(
            'salon.public',
            [
                'salon' =>
                    $salon->slug,
            ]
        );
    }


    /*
    |--------------------------------------------------------------------------
    | Render QR
    |--------------------------------------------------------------------------
    */

    /**
     * Render QR as SVG.
     */
    private function renderQr(
        string $url,
        int $scale = 8
    ): string {
        /*
        |--------------------------------------------------------------------------
        | QR Options
        |--------------------------------------------------------------------------
        */

        $options =
            new QROptions();


        /*
        |--------------------------------------------------------------------------
        | SVG Output
        |--------------------------------------------------------------------------
        */

        $options->outputInterface =
            QRMarkupSVG::class;

        $options->outputBase64 =
            false;


        /*
        |--------------------------------------------------------------------------
        | Error Correction
        |--------------------------------------------------------------------------
        */

        $options->eccLevel =
            'H';


        /*
        |--------------------------------------------------------------------------
        | Quiet Zone
        |--------------------------------------------------------------------------
        */

        $options->addQuietzone =
            true;


        /*
        |--------------------------------------------------------------------------
        | Scale
        |--------------------------------------------------------------------------
        */

        $options->scale =
            max(
                1,
                $scale
            );


        /*
        |--------------------------------------------------------------------------
        | QR Code
        |--------------------------------------------------------------------------
        */

        $qrCode =
            new QRCode(
                $options
            );


        /*
        |--------------------------------------------------------------------------
        | Render
        |--------------------------------------------------------------------------
        */

        return $qrCode->render(
            $url
        );
    }


    /*
    |--------------------------------------------------------------------------
    | Image
    |--------------------------------------------------------------------------
    */

    /**
     * Render QR SVG inline.
     */
    public function image(): Response
    {
        /*
        |--------------------------------------------------------------------------
        | Current Salon
        |--------------------------------------------------------------------------
        */

        $salon = Auth::user()?->salon;

        abort_if(
            !$salon,
            404
        );


        /*
        |--------------------------------------------------------------------------
        | QR Must Exist
        |--------------------------------------------------------------------------
        */

        abort_if(
            blank(
                $salon->qr_token
            ),
            404
        );


        /*
        |--------------------------------------------------------------------------
        | Public URL
        |--------------------------------------------------------------------------
        */

        $publicUrl =
            $this->publicUrl(
                $salon
            );


        /*
        |--------------------------------------------------------------------------
        | Render
        |--------------------------------------------------------------------------
        */

        $svg =
            $this->renderQr(
                $publicUrl,
                8
            );


        /*
        |--------------------------------------------------------------------------
        | Response
        |--------------------------------------------------------------------------
        */

        return response(
            $svg,
            200,
            [
                'Content-Type' =>
                    'image/svg+xml; charset=UTF-8',

                'Content-Disposition' =>
                    'inline; filename="salon-qr.svg"',

                'Cache-Control' =>
                    'private, max-age=3600',

                'X-Content-Type-Options' =>
                    'nosniff',
            ]
        );
    }


    /*
    |--------------------------------------------------------------------------
    | Download
    |--------------------------------------------------------------------------
    */

    /**
     * Download QR SVG.
     */
    public function download(): Response
    {
        /*
        |--------------------------------------------------------------------------
        | Current Salon
        |--------------------------------------------------------------------------
        */

        $salon = Auth::user()?->salon;

        abort_if(
            !$salon,
            404
        );


        /*
        |--------------------------------------------------------------------------
        | QR Must Exist
        |--------------------------------------------------------------------------
        */

        abort_if(
            blank(
                $salon->qr_token
            ),
            404
        );


        /*
        |--------------------------------------------------------------------------
        | Public URL
        |--------------------------------------------------------------------------
        */

        $publicUrl =
            $this->publicUrl(
                $salon
            );


        /*
        |--------------------------------------------------------------------------
        | High Resolution QR
        |--------------------------------------------------------------------------
        */

        $svg =
            $this->renderQr(
                $publicUrl,
                12
            );


        /*
        |--------------------------------------------------------------------------
        | Filename
        |--------------------------------------------------------------------------
        */

        $filename =
            Str::slug(
                $salon->name
                    ?: 'salon'
            )
            . '-qr.svg';


        /*
        |--------------------------------------------------------------------------
        | Download Response
        |--------------------------------------------------------------------------
        */

        return response(
            $svg,
            200,
            [
                'Content-Type' =>
                    'image/svg+xml; charset=UTF-8',

                'Content-Disposition' =>
                    'attachment; filename="' .
                    $filename .
                    '"',

                'Cache-Control' =>
                    'no-cache, no-store, must-revalidate',

                'X-Content-Type-Options' =>
                    'nosniff',
            ]
        );
    }
}
