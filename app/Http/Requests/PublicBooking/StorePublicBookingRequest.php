<?php

namespace App\Http\Requests\PublicBooking;

use Illuminate\Foundation\Http\FormRequest;

class StorePublicBookingRequest extends FormRequest
{
    /**
     * Public booking does not require authentication.
     */
    public function authorize(): bool
    {
        return true;
    }


    /**
     * Normalize input before validation.
     */
    protected function prepareForValidation(): void
    {
        /*
        |--------------------------------------------------------------------------
        | Normalize Customer Phone
        |--------------------------------------------------------------------------
        |
        | Persian digits are converted to English digits.
        |
        */

        $phone = (string) $this->input(
            'customer_phone'
        );

        $phone = strtr($phone, [
            '۰' => '0',
            '۱' => '1',
            '۲' => '2',
            '۳' => '3',
            '۴' => '4',
            '۵' => '5',
            '۶' => '6',
            '۷' => '7',
            '۸' => '8',
            '۹' => '9',
        ]);

        $this->merge([
            'customer_phone' => trim($phone),
        ]);
    }


    /**
     * Validation rules.
     */
    public function rules(): array
    {
        return [

            /*
            |--------------------------------------------------------------------------
            | Service
            |--------------------------------------------------------------------------
            */

            'service_id' => [
                'required',
                'integer',
            ],


            /*
            |--------------------------------------------------------------------------
            | Booking Date
            |--------------------------------------------------------------------------
            */

            'booking_date' => [
                'required',
                'string',
                'max:10',
            ],


            /*
            |--------------------------------------------------------------------------
            | Booking Time
            |--------------------------------------------------------------------------
            */

            'booking_time' => [
                'required',
                'date_format:H:i',
            ],


            /*
            |--------------------------------------------------------------------------
            | Customer Name
            |--------------------------------------------------------------------------
            */

            'customer_name' => [
                'required',
                'string',
                'min:2',
                'max:255',
            ],


            /*
            |--------------------------------------------------------------------------
            | Customer Phone
            |--------------------------------------------------------------------------
            |
            | Iranian mobile number:
            |
            | Exactly 11 digits
            | Starts with 09
            |
            */

            'customer_phone' => [
                'required',
                'string',
                'regex:/^09\d{9}$/',
            ],


            /*
            |--------------------------------------------------------------------------
            | Customer Note
            |--------------------------------------------------------------------------
            */

            'customer_note' => [
                'nullable',
                'string',
                'max:1000',
            ],
        ];
    }


    /**
     * Custom validation messages.
     */
    public function messages(): array
    {
        return [

            /*
            |--------------------------------------------------------------------------
            | Service
            |--------------------------------------------------------------------------
            */

            'service_id.required' =>
                'لطفاً یک خدمت را انتخاب کنید.',

            'service_id.integer' =>
                'خدمت انتخاب‌شده معتبر نیست.',


            /*
            |--------------------------------------------------------------------------
            | Booking Date
            |--------------------------------------------------------------------------
            */

            'booking_date.required' =>
                'لطفاً تاریخ رزرو را انتخاب کنید.',

            'booking_date.string' =>
                'فرمت تاریخ رزرو معتبر نیست.',

            'booking_date.max' =>
                'تاریخ رزرو معتبر نیست.',


            /*
            |--------------------------------------------------------------------------
            | Booking Time
            |--------------------------------------------------------------------------
            */

            'booking_time.required' =>
                'لطفاً ساعت رزرو را انتخاب کنید.',

            'booking_time.date_format' =>
                'فرمت ساعت رزرو باید به صورت ساعت:دقیقه باشد.',


            /*
            |--------------------------------------------------------------------------
            | Customer Name
            |--------------------------------------------------------------------------
            */

            'customer_name.required' =>
                'لطفاً نام خود را وارد کنید.',

            'customer_name.string' =>
                'نام واردشده معتبر نیست.',

            'customer_name.min' =>
                'نام باید حداقل ۲ کاراکتر باشد.',

            'customer_name.max' =>
                'نام نمی‌تواند بیشتر از ۲۵۵ کاراکتر باشد.',


            /*
            |--------------------------------------------------------------------------
            | Customer Phone
            |--------------------------------------------------------------------------
            */

            'customer_phone.required' =>
                'لطفاً شماره موبایل خود را وارد کنید.',

            'customer_phone.string' =>
                'شماره موبایل واردشده معتبر نیست.',

            'customer_phone.regex' =>
                'شماره موبایل باید ۱۱ رقمی و با 09 شروع شود.',


            /*
            |--------------------------------------------------------------------------
            | Customer Note
            |--------------------------------------------------------------------------
            */

            'customer_note.string' =>
                'توضیحات باید به صورت متن باشد.',

            'customer_note.max' =>
                'توضیحات نمی‌تواند بیشتر از ۱۰۰۰ کاراکتر باشد.',
        ];
    }


    /**
     * Custom attribute names.
     */
    public function attributes(): array
    {
        return [

            'service_id' =>
                'خدمت',

            'booking_date' =>
                'تاریخ رزرو',

            'booking_time' =>
                'ساعت رزرو',

            'customer_name' =>
                'نام',

            'customer_phone' =>
                'شماره موبایل',

            'customer_note' =>
                'توضیحات',
        ];
    }
}
